-- LLM 요약·분류 결과 테이블 (v1)
-- raw_article 1건당 요약 1건 (uq 제약으로 재처리 시 중복 방지 = 멱등성)
CREATE TABLE article_summary (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_article_id BIGINT       NOT NULL REFERENCES raw_article(id),
    category       VARCHAR(30)  NOT NULL,   -- Category enum 이름(AI/DEV/CLOUD_INFRA/SECURITY/ETC)
    summary        TEXT         NOT NULL,
    model          VARCHAR(50)  NOT NULL,   -- 어떤 모델로 처리했는지 기록
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_article_summary_raw UNIQUE (raw_article_id)
);

CREATE INDEX idx_article_summary_category ON article_summary (category);
